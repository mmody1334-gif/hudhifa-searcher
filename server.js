// محرك بديل فوري في حال تعذر اتصال السيرفر بـ Gemini
function getFallbackAnswer(q) {
  const cq = q.replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').toLowerCase();

  if (cq.includes('محمد مجدي') || cq.includes('خضير') || cq.includes('احياء')) {
    return `### بيانات المعلم:\n* **الاسم الكامل:** الأستاذ محمد مجدي محمد حسن خضير (مصري الجنسية).\n* **الوظيفة والتخصص:** معلم مادة الأحياء بالمدرسة، ويدرس أيضاً مادة العلوم البيئية للصف الثاني عشر.\n\n### نتائج المادة في التقرير (الفصل الثاني 2025/2026):\n* **الصف التاسع:** نسبة إتقان 77% (متميز).\n* **الصف العاشر:** نسبة إتقان 48% (غير ملائم - يحتاج لخطة تحسين).\n* **الصف الحادي عشر:** نسبة إتقان 100% (متميز لجميع الطلبة).\n* **الصف الثاني عشر:** غير مسجلة بالجداول.`;
  }

  if (cq.includes('عاشر') || cq.includes('العاشر')) {
    return `### نتائج ونسب إتقان الصف العاشر (19 طالباً):\n* الدراسات الاجتماعية: 90% (متميز)\n* اللغة العربية: 74% (متميز)\n* التربية الإسلامية: 58% (ملائم)\n* الأحياء: 48% (غير ملائم)\n* الفيزياء: 37% (تدخل سريع)\n* اللغة الإنجليزية: 26% (تدخل سريع)\n* الكيمياء: 11% (غير ملائم)\n* الرياضيات العامة: 5% (تدخل سريع - طالب واحد فقط).`;
  }

  if (cq.includes('معمري') || cq.includes('عبدالله') || cq.includes('ابراهيم')) {
    return `### المعلمون من عائلة المعمري في المدرسة:\n* **أ/ عبد الله بن سيف بن سبيت المعمري:** معلم مادة الكيمياء.\n* **أ/ يوسف بن عبد الله بن يوسف المعمري:** معلم مادة الفيزياء.\n* **أ/ ابراهيم بن سعيد بن عبد الله المعمري:** معلم مادة اللغة العربية.`;
  }

  return `المعلومات متاحة في تقرير التقويم الذاتي لمدرسة حذيفة بن محصن (5-12) للعام 2026/2027م تحت إشراف د. بدر الكعبي. يضم التقرير 139 طالباً و19 معلماً، وتفاصيل دقيقة عن كافة المواد والمشاريع المدرسية.`;
}

app.post('/api/chat', async (req, res) => {
  try {
    const { message } = req.body;
    if (!message) return res.status(400).json({ error: 'الرجاء كتابة سؤال.' });

    // تجربة الموديلات المستقرة بالترتيب
    const models = ['gemini-1.5-flash', 'gemini-1.5-pro', 'gemini-2.0-flash'];
    const prompt = `${SYSTEM_PROMPT}\n\nسؤال المستخدم: ${message}`;

    for (const m of models) {
      try {
        const model = genAI.getGenerativeModel({ model: m });
        const result = await model.generateContent(prompt);
        const response = await result.response;
        return res.json({ reply: response.text() });
      } catch (err) {
        console.warn(`فشل النموذج ${m}، المحاولة مع النموذج التالي...`);
      }
    }

    // إذا تعثرت كل الموديلات بسبب الضغط، يتم الرد فوراً بالبديل
    res.json({ reply: getFallbackAnswer(message) });
  } catch (error) {
    console.error("Chat Error:", error);
    res.json({ reply: getFallbackAnswer(req.body.message || '') });
  }
});

const PORT = process.env.PORT || 3000;
app.listen(PORT, () => console.log(`الخادم يعمل على المنفذ ${PORT}`));
